const repairMisionesLocalityText = (value: string) =>
  MISiones_MOJIBAKE_REPLACEMENTS.reduce(
    (text, [broken, correct]) => text.replaceAll(broken, correct),
    value,
  );

const expandMisionesLocalityAbbreviations = (value: string) =>
  repairMisionesLocalityText(value)
    .toUpperCase()
    .replace(/\bCNIA./g, "COLONIA ")
    .replace(/\bPTO./g, "PUERTO ")
    .replace(/\bSTA./g, "SANTA ")
    .replace(/\bSTO./g, "SANTO ")
    .replace(/\bVA\./g, "VILLA ")
    .replace(/\bGRAL./g, "GENERAL ")
    .replace(/\bGDOR./g, "GOBERNADOR ")
    .replace(/\bALMTE./g, "ALMIRANTE ")
    .replace(/\bCMTE./g, "COMANDANTE ")
    .replace(/\bMTE./g, "MONTE ")
    .replace(/\bNVA./g, "NUEVA ")
    .replace(/\bPBLO./g, "PUEBLO ")
    .replace(/\bCAPT./g, "CAPITAN ")
    .replace(/\bEST./g, "ESTACION ")
    .replace(/\bLIB.GRAL.S.MARTIN\b/g, "LIBERTADOR GENERAL SAN MARTIN")
    .replace(/\bL.N.ALEM\b/g, "LEANDRO N. ALEM")
    .replace(/\bB.DE IRIGOYEN\b/g, "BERNARDO DE IRIGOYEN")
    .replace(/\bDTO.S.J\b/g, "DEPARTAMENTO SAN JAVIER")
    .replace(/\s+/g, " ")
    .trim();


const MISiones_LOCALITY_CANONICAL_ALIASES: ReadonlyArray<readonly [string, string]> = [
  ["PUEETO IGUAZU", "PUERTO IGUAZÚ"],
  ["PTO IGUAZU", "PUERTO IGUAZÚ"],
  ["PUERTO IGUAZU", "PUERTO IGUAZÚ"],
  ["LEANDRO N.ALEM", "LEANDRO N. ALEM"],
  ["LEANDRO N ALEM", "LEANDRO N. ALEM"],
  ["ARISTOBULO DEL VALLE", "ARISTÓBULO DEL VALLE"],
  ["COLONIA ARISTOBULO DEL VALLE", "COLONIA ARISTÓBULO DEL VALLE"],
  ["SANTA RITA, ALBA POSSE", "ALBA POSSE"],
];

const canonicalizeMisionesLocality = (value: string) => {
  const normalized = expandMisionesLocalityAbbreviations(value);
  return MISiones_LOCALITY_CANONICAL_ALIASES.find(([alias]) => alias === normalized)?.[1] || normalized;
};

export const normalizeMisionesLocality = (value: unknown) => canonicalizeMisionesLocality(String(value ?? ""));

export const MISIONES_LOCALITY_OPTIONS = Array.from(
  new Set(
    MISIONES_LOCALITIES_WITH_POSTAL_CODE
      .map(([locality]) => normalizeMisionesLocality(locality))
      .filter(Boolean),
  ),
).sort((left, right) => left.localeCompare(right, "es"));

export const MISIONES_LOCALITY_SET = new Set(MISIONES_LOCALITY_OPTIONS);

export const MISIONES_LOCALITY_POSTAL_BY_NAME = MISIONES_LOCALITIES_WITH_POSTAL_CODE.reduce<Record<string, string>>((result, [locality, postal]) => {
  const normalized = normalizeMisionesLocality(locality);
  if (normalized && !result[normalized]) result[normalized] = postal;
  return result;
}, {});